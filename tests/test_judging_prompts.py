"""The prompt table is data, and these are the pins that keep it data.

Every digest below was computed from the frozen record's own expressions: the
donor scripts' literals, and for the two system prompts the donor's own f-string,
evaluated and compared byte for byte. A failure here is not a style regression.
It means a judged number in the record was taken under a different question than
the one this repository says it was taken under, and the number and the question
have come apart.
"""

